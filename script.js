const homeView = document.getElementById("homeView");
const dictionaryView = document.getElementById("dictionaryView");
const categoryHeading = document.getElementById("categoryHeading");
const categoryDescription = document.getElementById("categoryDescription");
const deviceGrid = document.getElementById("deviceGrid");
const resultCount = document.getElementById("resultCount");
const modal = document.getElementById("deviceModal");
const modalBackdrop = document.getElementById("modalBackdrop");
const modalClose = document.getElementById("modalClose");
const modalImage = document.getElementById("modalImage");
const modalCategory = document.getElementById("modalCategory");
const modalTitle = document.getElementById("modalTitle");
const modalDescription = document.getElementById("modalDescription");
const modalExample = document.getElementById("modalExample");

let activeCategory = "input";
let lastFocusedElement = null;

function openCategory(category) {
  activeCategory = category;
  const selected = deviceData[category];
  categoryHeading.textContent = selected.title;
  categoryDescription.textContent = selected.description;
  homeView.classList.add("hidden");
  dictionaryView.classList.remove("hidden");
  renderDevices();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderDevices() {
  const devices = [...deviceData[activeCategory].devices].sort((a, b) => a[0].localeCompare(b[0]));
  deviceGrid.innerHTML = "";
  devices.forEach(([name, description, example, imageLabel]) => {
    const image = imageUrl(imageLabel, activeCategory);
    const card = document.createElement("button");
    card.type = "button";
    card.className = "device-card";
    card.setAttribute("aria-label", `View details for ${name}`);

    const imageWrap = document.createElement("div");
    imageWrap.className = "device-card-image";
    const img = document.createElement("img");
    img.src = image;
    img.alt = name;
    img.loading = "lazy";
    imageWrap.appendChild(img);

    const info = document.createElement("div");
    info.className = "device-card-info";
    const title = document.createElement("h2");
    title.textContent = name;
    const desc = document.createElement("p");
    desc.textContent = description;
    const link = document.createElement("span");
    link.className = "card-link";
    link.textContent = "View details ↗";
    info.append(title, desc, link);
    card.append(imageWrap, info);
    card.addEventListener("click", () => openDeviceModal({ name, description, example, image }));
    deviceGrid.appendChild(card);
  });
  resultCount.textContent = `${devices.length} ${devices.length === 1 ? "device" : "devices"}`;
}

function openDeviceModal(device) {
  lastFocusedElement = document.activeElement;
  modalCategory.textContent = deviceData[activeCategory].title.toUpperCase();
  modalTitle.textContent = device.name;
  modalDescription.textContent = device.description;
  modalExample.textContent = device.example;
  modalImage.src = device.image;
  modalImage.alt = device.name;
  modal.classList.remove("hidden");
  document.body.classList.add("modal-open");
  modalClose.focus();
}

function closeDeviceModal() {
  modal.classList.add("hidden");
  document.body.classList.remove("modal-open");
  if (lastFocusedElement) lastFocusedElement.focus();
}

document.querySelectorAll("[data-category]").forEach(button => {
  button.addEventListener("click", () => openCategory(button.dataset.category));
});

function goHome() {
  closeDeviceModal();
  dictionaryView.classList.add("hidden");
  homeView.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });
}
document.getElementById("backButton").addEventListener("click", goHome);
document.getElementById("homeLink").addEventListener("click", event => {
  event.preventDefault();
  goHome();
});
modalClose.addEventListener("click", closeDeviceModal);
modalBackdrop.addEventListener("click", closeDeviceModal);
document.addEventListener("keydown", event => {
  if (event.key === "Escape" && !modal.classList.contains("hidden")) closeDeviceModal();
});